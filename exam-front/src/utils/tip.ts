/**
 * 提示文案清洗
 *
 * <p>后端给的 tip 为了把事情说全，会夹带括号里的时间，例如
 * 「已超过最晚入场时间（10-01 21:25 前入场），无法参加本次考试」。
 * 前端卡片和说明页空间有限，具体时间已经由倒计时体现了，
 * 这里统一压成一句话：「已超过最晚入场时间，无法参加本次考试」。
 */

/**
 * 去掉括号补充说明与多余的标点，只留主干
 *
 * @param text 后端下发的 tip，可能带「（最晚 xx:xx 前入场）」这类补充
 */
export const plainTip = (text?: string): string =>
  (text ?? '')
    // 去掉中英文括号及其中的内容
    .replace(/[（(][^（()）]*[）)]/g, '')
    // 顺手清掉括号留下的空档与重复/悬空的逗号
    .replace(/\s{2,}/g, ' ')
    .replace(/，{2,}/g, '，')
    .replace(/^[，、；\s]+|[，、；\s]+$/g, '')
    .trim();
